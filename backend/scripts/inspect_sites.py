"""Inspect the official sites from YOUR machine and write backend/docs/crawl_findings.md.

    python -m scripts.inspect_sites

Reports robots.txt, sitemap, and whether each home page is static HTML or a JavaScript shell,
so you know which crawl fallback (embedded JSON / public API / Playwright) is needed.
"""
import re
import sys
from pathlib import Path
from urllib.parse import urlparse

from app.core.config import BACKEND_DIR, get_settings
from app.services.crawler import Crawler, extract_page, text_from_json

OUT = BACKEND_DIR / "docs" / "crawl_findings.md"


def inspect(settings, crawler: Crawler, url: str) -> list[str]:
    origin = "{0.scheme}://{0.netloc}".format(urlparse(url))
    lines = [f"## {origin}", ""]
    try:
        r = crawler._get(origin + "/robots.txt")
        lines.append(f"- robots.txt: HTTP {r.status_code}" + (f" ({len(r.text.splitlines())} lines)" if r.status_code == 200 else ""))
        if r.status_code == 200:
            lines += [f"  - `{l}`" for l in r.text.splitlines() if l.lower().startswith(("disallow", "sitemap", "crawl-delay"))][:15]
    except Exception as e:
        lines.append(f"- robots.txt: UNREACHABLE ({type(e).__name__})")
    sm = crawler._sitemap_urls(origin)
    lines.append(f"- sitemap URLs found: {len(sm)}" + (f" (e.g. {sm[0]})" if sm else ""))
    try:
        r = crawler._get(url)
        if r.status_code != 200:
            lines.append(f"- home page: HTTP {r.status_code}")
            return lines + [""]
        info = extract_page(r.text, url)
        blob = sum(len(text_from_json(b)) for b in info["json_blobs"])
        api = sorted(set(re.findall(r"""["'](/api/[^"'\s<>\\]+)["']""", info["scripts_text"])))[:5]
        kind = "static HTML" if len(info["text"]) >= settings.crawl_min_text_chars else "JavaScript shell (little static text)"
        lines += [f"- home page: HTTP 200, {kind}; static text chars: {len(info['text'])}; embedded JSON text chars: {blob}",
                  f"- public /api/ paths referenced in scripts: {api or 'none'}",
                  f"- internal links on page: {len([l for l in info['links'] if crawler.in_scope(l)])}",
                  "- recommended fallback: " + ("none needed" if kind == "static HTML" else
                    "embedded JSON" if blob >= settings.crawl_min_text_chars else "public API" if api else "Playwright (ENABLE_PLAYWRIGHT=true)")]
    except Exception as e:
        lines.append(f"- home page: UNREACHABLE ({type(e).__name__})")
    return lines + [""]


def main() -> int:
    s = get_settings()
    cr = Crawler(s)
    out = ["# Crawl findings", "", "Generated by `python -m scripts.inspect_sites`. YouTube is ingested through the official API only (no scraping).", ""]
    for seed in s.seed_urls:
        out += inspect(s, cr, seed)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
